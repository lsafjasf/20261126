var (
	glyphCache   = make(map[rune]bitmapGlyph)
	glyphCacheMu sync.RWMutex
)

func glyphFor(r rune) bitmapGlyph {
	glyphCacheMu.RLock()
	if glyph, ok := glyphCache[r]; ok {
		glyphCacheMu.RUnlock()
		return glyph
	}
	glyphCacheMu.RUnlock()
	lookup := r
	if lookup < 128 {
		lookup = unicode.ToUpper(lookup)
	}
	pattern, ok := glyphPatterns[lookup]
	if !ok {
		pattern = "11111/10001/10001/10001/10001/10001/11111"
	}
	var glyph bitmapGlyph
	rows := splitSeven(pattern)
	for y, row := range rows {
		for x, bit := range row {
			glyph[y][x] = bit == '1'
		}
	}
	glyphCacheMu.Lock()
	glyphCache[r] = glyph
	glyphCacheMu.Unlock()
	return glyph
}

func splitSeven(pattern string) []string {
	rows := make([]string, 0, 7)
	start := 0
	for i := 0; i <= len(pattern); i++ {
		if i == len(pattern) || pattern[i] == '/' {
			rows = append(rows, pattern[start:i])
			start = i + 1
		}
	}
	for len(rows) < 7 {
		rows = append(rows, "00000")
	}
	return rows[:7]
}
