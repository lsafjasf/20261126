package sdh

import (
	"fmt"
	"strings"
)

// ASSOptions controls the layered ASS renderer.
type ASSOptions struct {
	Width       int
	Height      int
	FontName    string
	FontSize    int
	MarginL     int
	MarginR     int
	BaseMarginV int
}

// DefaultASSOptions returns 1920x1080 defaults using a CJK-capable font.
func DefaultASSOptions() ASSOptions {
	return ASSOptions{
		Width:       1920,
		Height:      1080,
		FontName:    "Droid Sans Fallback",
		FontSize:    60,
		MarginL:     120,
		MarginR:     120,
		BaseMarginV: 56,
	}
}

type assStyleSpec struct {
	role   Role
	lane   int
	margin int
}

// RenderASS renders the project as an ASS/SSA document. Each semantic role
// gets its own style (color/italic/alignment); overlap lanes become distinct
// MarginV values via per-lane styles so simultaneous entries never share a
// visual line.
func RenderASS(p *Project, opts ASSOptions) []byte {
	if p == nil {
		return nil
	}
	if opts.Width <= 0 {
		opts.Width = 1920
	}
	if opts.Height <= 0 {
		opts.Height = 1080
	}
	if opts.FontSize <= 0 {
		opts.FontSize = opts.Height / 18
	}
	if opts.FontName == "" {
		opts.FontName = "Droid Sans Fallback"
	}

	lineHeight := int(float64(opts.FontSize) * 1.35)
	laneGap := opts.FontSize / 4

	// Estimate wrapped line counts and the tallest occupancy per lane.
	laneLines := map[Anchor]map[int]int{}
	usedStyles := map[assStyleSpec]bool{}
	for _, entry := range p.Entries {
		anchor := entry.Role.Anchor()
		if laneLines[anchor] == nil {
			laneLines[anchor] = map[int]int{}
		}
		lines := estimateTextLines(entry.Text, opts)
		if lines > laneLines[anchor][entry.Lane] {
			laneLines[anchor][entry.Lane] = lines
		}
		usedStyles[assStyleSpec{entry.Role, entry.Lane, 0}] = true
	}

	marginFor := map[Anchor]map[int]int{}
	for anchor, lanes := range laneLines {
		marginFor[anchor] = map[int]int{}
		acc := opts.BaseMarginV
		for lane := 0; lane < len(lanes); lane++ {
			marginFor[anchor][lane] = acc
			acc += lanes[lane]*lineHeight + laneGap
		}
	}

	var b strings.Builder
	b.WriteString("[Script Info]\n")
	b.WriteString("; Generated by sdh layered subtitle toolkit\n")
	b.WriteString("ScriptType: v4.00+\n")
	fmt.Fprintf(&b, "PlayResX: %d\n", opts.Width)
	fmt.Fprintf(&b, "PlayResY: %d\n", opts.Height)
	b.WriteString("WrapStyle: 0\n")
	b.WriteString("ScaledBorderAndShadow: yes\n\n")

	b.WriteString("[V4+ Styles]\n")
	b.WriteString("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n")

	specs := make([]assStyleSpec, 0, len(usedStyles))
	for spec := range usedStyles {
		spec.margin = marginFor[spec.role.Anchor()][spec.lane]
		specs = append(specs, spec)
	}
	sortStyleSpecs(specs)
	for _, spec := range specs {
		b.WriteString(renderASSStyle(opts, spec))
		b.WriteByte('\n')
	}
	b.WriteByte('\n')

	b.WriteString("[Events]\n")
	b.WriteString("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n")
	for _, entry := range p.Entries {
		styleName := assStyleName(entry.Role, entry.Lane)
		name := strings.ReplaceAll(entry.Speaker, ",", " ")
		fmt.Fprintf(&b, "Dialogue: %d,%s,%s,%s,%s,0,0,0,,%s\n",
			roleMetadata[entry.Role].assLayer,
			FormatASSTime(entry.Start),
			FormatASSTime(entry.End),
			styleName,
			name,
			assEscape(entry.Text),
		)
	}
	return []byte(b.String())
}

func sortStyleSpecs(specs []assStyleSpec) {
	for i := 1; i < len(specs); i++ {
		for j := i; j > 0; j-- {
			if styleSpecLess(specs[j], specs[j-1]) {
				specs[j], specs[j-1] = specs[j-1], specs[j]
			}
		}
	}
}

func styleSpecLess(a, b assStyleSpec) bool {
	if roleOrder(a.role) != roleOrder(b.role) {
		return roleOrder(a.role) < roleOrder(b.role)
	}
	return a.lane < b.lane
}

func assStyleName(role Role, lane int) string {
	return fmt.Sprintf("SDH_%s_L%d", titleToken(string(role)), lane)
}

func titleToken(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	if r[0] >= 'a' && r[0] <= 'z' {
		r[0] -= 'a' - 'A'
	}
	return string(r)
}

type assLook struct {
	primary string
	bold    int
	italic  int
	align   int
}

func roleLook(role Role) assLook {
	switch role {
	case RoleSpeaker:
		return assLook{primary: "&H0000FFFF", bold: 1, align: 2} // yellow
	case RoleSound:
		return assLook{primary: "&H0090EE90", italic: 1, align: 8} // light green, top
	case RoleMusic:
		return assLook{primary: "&H0000A5FF", italic: 1, align: 8} // orange, top
	case RoleLyric:
		return assLook{primary: "&H00C3B6FF", italic: 1, align: 2} // light pink
	case RoleVoiceOver:
		return assLook{primary: "&H00FFFFD0", align: 2} // light cyan (BGR)
	default:
		return assLook{primary: "&H00FFFFFF", align: 2} // white
	}
}

func renderASSStyle(opts ASSOptions, spec assStyleSpec) string {
	look := roleLook(spec.role)
	return fmt.Sprintf(
		"Style: %s,%s,%d,%s,&H000000FF,&H00101010,&H64000000,%d,%d,0,0,100,100,0,0,1,2.4,0,%d,%d,%d,%d,1",
		assStyleName(spec.role, spec.lane),
		opts.FontName,
		opts.FontSize,
		look.primary,
		look.bold,
		look.italic,
		look.align,
		opts.MarginL,
		opts.MarginR,
		spec.margin,
	)
}

// estimateTextLines approximates wrapping using 1 unit per Latin glyph and
// 2 units per CJK/full-width glyph.
func estimateTextLines(text string, opts ASSOptions) int {
	usablePx := opts.Width - opts.MarginL - opts.MarginR
	unitsPerLine := float64(usablePx) / (float64(opts.FontSize) * 0.52)
	if unitsPerLine < 8 {
		unitsPerLine = 8
	}
	total := 0
	for _, hard := range strings.Split(text, "\n") {
		units := 0.0
		for _, r := range hard {
			if isCJK(r) {
				units += 2
			} else {
				units++
			}
		}
		lines := int(units / unitsPerLine)
		if float64(int(units)) > float64(lines)*unitsPerLine {
			lines++
		}
		if lines < 1 {
			lines = 1
		}
		total += lines
	}
	if total < 1 {
		total = 1
	}
	return total
}

func assEscape(text string) string {
	text = strings.ReplaceAll(text, "\r", "")
	text = strings.ReplaceAll(text, "\n", "\\N")
	text = strings.ReplaceAll(text, "{", "(")
	text = strings.ReplaceAll(text, "}", ")")
	return text
}
